#!/usr/bin/env bun
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { adaptGuidance } from './impeccable/guidance.ts';

const repoRoot = path.resolve(import.meta.dir, '..');
let passed = 0;

function test(name: string, run: (dir: string) => void) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'impeccable-test-'));
  try {
    run(dir);
    passed += 1;
    console.log(`ok - ${name}`);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function snapshot(dir: string): unknown {
  return fs.readdirSync(dir).sort().map(name => {
    const file = path.join(dir, name);
    return [name, fs.statSync(file).isDirectory() ? snapshot(file) : fs.readFileSync(file).toString('base64')];
  });
}

test('should remove native administration when generating APM guidance', () => {
  const skillDir = path.join(repoRoot, 'packages/impeccable/.apm/skills/impeccable');
  const files = ['SKILL.md', 'reference/doctor.md', 'reference/hooks.md', 'reference/live.md', 'reference/generate.md'];
  const bodies = files.map(file => fs.readFileSync(path.join(skillDir, file), 'utf8'));

  for (const [index, body] of bodies.entries()) {
    assert.doesNotMatch(body, /npx impeccable (?:install|update)|impeccable pin |hooks (?:on|reset)|Pin \/ Unpin/, 'generated guidance must not recommend native administration');
    assert.doesNotMatch(body, /do not run native install/, 'blanket overlay must be absent');
    for (const match of body.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
      const link = match[1].split('#')[0];
      if (!link || /^https?:/.test(link)) continue;
      assert.ok(fs.existsSync(path.resolve(skillDir, path.dirname(files[index]), link)), `local link must resolve: ${files[index]} -> ${link}`);
    }
  }
  assert.match(bodies[1], /apm update.*apm install/, 'doctor must name the APM update path');
  assert.match(bodies[1], /doctor --fix/, 'project-document migration must remain available');
  assert.match(bodies[1], /design-md-dead-path/, 'useful project doctor findings must remain');
  assert.match(bodies[2], /ignore-value bounce-easing/, 'detector triage examples must remain');
  assert.doesNotMatch(bodies[0], /IMPECCABLE_LIVE_COPY_AGENT/, 'live policy must not load for every task');
  assert.match(bodies[3], /IMPECCABLE_LIVE_COPY_AGENT=chat/, 'live must require chat mode');
  assert.match(bodies[4], /IMPECCABLE_LIVE_COPY_AGENT=chat/, 'generate must require chat mode');
});

test('should reject upstream drift when guidance anchors change', () => {
  for (const file of ['SKILL.md', 'reference/doctor.md', 'reference/hooks.md', 'reference/live.md', 'reference/generate.md']) {
    assert.throws(() => adaptGuidance(file, '# Upstream changed'), /Upstream guidance anchor changed/, `missing anchors must fail for ${file}`);
  }
});

test('should regenerate identical packages when built twice', dir => {
  const build = () => Bun.spawnSync(['bun', 'scripts/build-impeccable-package.ts', '--out', dir], { cwd: repoRoot });

  const deployedChild = path.join(dir, 'impeccable/claude/.claude/deployment-marker');
  fs.mkdirSync(path.dirname(deployedChild), { recursive: true });
  fs.writeFileSync(deployedChild, 'preserve child deployment');

  const firstBuild = build();
  assert.equal(firstBuild.exitCode, 0, `build must succeed: ${firstBuild.stderr}`);
  const first = snapshot(dir);

  const secondBuild = build();
  assert.equal(secondBuild.exitCode, 0, `second build must succeed: ${secondBuild.stderr}`);
  assert.deepEqual(snapshot(dir), first, 'all generated bytes must match');
  assert.equal(fs.readFileSync(deployedChild, 'utf8'), 'preserve child deployment', 'umbrella regeneration must preserve child compiled output');
  for (const name of ['impeccable', 'impeccable/claude', 'impeccable/copilot']) {
    assert.deepEqual(snapshot(path.join(dir, name, '.apm')), snapshot(path.join(repoRoot, 'packages', name, '.apm')), 'primitive sources must match regeneration');
    for (const file of ['apm.yml', 'LICENSE', 'NOTICE.md']) {
      assert.equal(fs.readFileSync(path.join(dir, name, file), 'utf8'), fs.readFileSync(path.join(repoRoot, 'packages', name, file), 'utf8'), `${name}/${file} must match regeneration`);
    }
  }
  assert.deepEqual(fs.readdirSync(dir), ['impeccable'], 'only the umbrella may exist at the packages root');
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'impeccable/apm.yml'), 'utf8'));
  assert.deepEqual(manifest.dependencies.apm, [
    { path: './claude', alias: 'impeccable-claude' },
    { path: './copilot', alias: 'impeccable-copilot' },
  ], 'nested dependencies must preserve their deployed identities');
  for (const target of ['claude', 'copilot']) {
    const child = JSON.parse(fs.readFileSync(path.join(dir, 'impeccable', target, 'apm.yml'), 'utf8'));
    assert.equal(child.name, `impeccable-${target}`, 'child package identity must remain stable');
    assert.deepEqual(child.targets, [target], 'child primitives must be restricted to their native harness');
  }
  assert.equal(fs.existsSync(path.join(dir, 'impeccable/.apm/instructions')), false, 'no always-on instruction may ship');
  for (const file of ['impeccable', 'impeccable.cmd']) {
    assert.match(fs.readFileSync(path.join(dir, 'impeccable/.apm/skills/impeccable/scripts', file), 'utf8'), /IMPECCABLE_NO_UPDATE_CHECK=1/, 'launchers must disable native update recommendations');
  }

  for (const [target, native] of [['claude', 'claude-code/.claude'], ['copilot', 'github/.github']]) {
    const agentsDir = path.join(dir, `impeccable/${target}/.apm/agents`);
    assert.equal(fs.readdirSync(agentsDir).length, 5, 'each harness must have five native agents');
    for (const file of fs.readdirSync(path.join(repoRoot, 'vendor/impeccable/dist', native, 'agents'))) {
      const body = fs.readFileSync(path.join(repoRoot, 'vendor/impeccable/dist', native, 'agents', file), 'utf8')
        .replaceAll('.claude/skills/impeccable/', '<skill-base-dir>/')
        .replaceAll('.github/skills/impeccable/', '<skill-base-dir>/');
      assert.equal(fs.readFileSync(path.join(agentsDir, file.replace(/(?:\.agent)?\.md$/, '.agent.md')), 'utf8'), body, 'complete native body and metadata must survive normalization');
    }
  }
});

test('should expose the executed adapter when native hook discovery reads descriptors', () => {
  for (const target of ['claude', 'copilot']) {
    const hookDir = path.join(repoRoot, `packages/impeccable/${target}/.apm/hooks`);
    const descriptor = JSON.parse(fs.readFileSync(path.join(hookDir, 'impeccable.json'), 'utf8'));
    for (const groups of Object.values(descriptor) as { hooks: { command: string }[] }[][]) {
      for (const group of groups) {
        for (const handler of group.hooks) {
          const match = handler.command.match(/^sh \.\/(skills\/impeccable\/scripts\/impeccable) hook(?:-before-edit)? /);
          assert.ok(match, 'descriptor must execute a native-recognizable launcher, not merely contain a marker');
          assert.ok(fs.existsSync(path.join(hookDir, match[1])), 'recognized adapter must exist for native doctor checks');
        }
      }
    }
  }
});

for (const [target, payload, harness] of [
  ['claude', { tool_name: 'Write', tool_input: { file_path: 'a.css', content: 'body{}' } }, 'claude'],
  ['copilot', { toolName: 'edit', toolArgs: '{"path":"a.css"}' }, 'github'],
  ['copilot', { tool_name: 'multi_replace_string_in_file', tool_input: { replacements: [{ filePath: 'a.css' }] } }, 'vscode'],
] as const) {
  for (const scope of ['project', 'global', 'user']) {
    test(`should preserve complete payload when ${harness} runs from nested cwd with ${scope} skills`, dir => {
      const project = path.join(dir, 'project');
      const cwd = path.join(project, 'src/nested');
      const home = path.join(dir, 'home');
      const installRoot = scope === 'project' ? project : home;
      const wrapperRoot = scope === 'global' ? home : project;
      const config = target === 'claude' ? '.claude' : '.github';
      const wrapper = path.join(wrapperRoot, config, target === 'claude' ? 'hooks/impeccable-claude/hook.cjs' : 'hooks/scripts/impeccable-copilot/hook.cjs');
      const launcher = path.join(installRoot, config, 'skills/impeccable/scripts/impeccable');
      fs.mkdirSync(cwd, { recursive: true });
      fs.mkdirSync(path.dirname(wrapper), { recursive: true });
      fs.mkdirSync(path.dirname(launcher), { recursive: true });
      fs.copyFileSync(path.join(repoRoot, 'scripts/impeccable/hook.cjs'), wrapper);
      const adapter = path.join(path.dirname(wrapper), 'skills/impeccable/scripts/impeccable');
      fs.mkdirSync(path.dirname(adapter), { recursive: true });
      fs.copyFileSync(path.join(repoRoot, 'scripts/impeccable/launcher.sh'), adapter);
      fs.writeFileSync(launcher, '#!/bin/sh\nprintf "%s\\n" "$IMPECCABLE_HOOK_HARNESS" "$IMPECCABLE_LIVE_COPY_AGENT" "$1" "$PWD"\ncat\n', { mode: 0o644 });
      const input = { ...payload, cwd, session_id: 'fixture', timestamp: 123, tool_response: { success: true } };

      const result = Bun.spawnSync(['sh', adapter, 'hook', target, 'PostToolUse'], {
        stdin: Buffer.from(JSON.stringify(input)),
        env: { ...process.env, HOME: home },
      });
      const [actualHarness, live, command, actualCwd, body] = result.stdout.toString().trim().split('\n');

      assert.equal(result.exitCode, 0, `stub must run without downloads: ${result.stderr}`);
      assert.equal(actualHarness, harness, 'engine must receive explicit harness');
      assert.equal(live, 'chat', 'live fallback must remain chat-only');
      assert.equal(command, 'hook', 'native verb must survive');
      assert.equal(actualCwd, cwd, 'engine must keep payload project cwd');
      assert.deepEqual(JSON.parse(body), { ...input, hook_event_name: 'PostToolUse' }, 'all payload metadata must survive');
    });
  }
}

for (const target of ['claude', 'copilot']) {
  test(`should emit setup guidance once when ${target} receives SessionStart`, dir => {
    const launcher = path.join(dir, target === 'claude' ? '.claude' : '.github', 'skills/impeccable/scripts/impeccable');
    fs.mkdirSync(path.dirname(launcher), { recursive: true });
    fs.writeFileSync(launcher, '#!/bin/sh\nexit 99\n', { mode: 0o755 });

    const hookDir = path.join(dir, target === 'claude' ? '.claude/hooks/impeccable-claude' : '.github/hooks/scripts/impeccable-copilot');
    const adapter = path.join(hookDir, 'skills/impeccable/scripts/impeccable');
    fs.mkdirSync(path.dirname(adapter), { recursive: true });
    fs.copyFileSync(path.join(repoRoot, 'scripts/impeccable/launcher.sh'), adapter);
    fs.copyFileSync(path.join(repoRoot, 'scripts/impeccable/hook.cjs'), path.join(hookDir, 'hook.cjs'));

    const result = Bun.spawnSync(['sh', adapter, 'hook', target, 'SessionStart'], { stdin: Buffer.from(JSON.stringify({ cwd: dir })) });

    assert.equal(result.exitCode, 0, `SessionStart must succeed: ${result.stderr}`);
    const output = JSON.parse(result.stdout.toString());
    assert.match(output.hookSpecificOutput.additionalContext, /once per session/, 'setup must not request context on every tool call');
    assert.equal(output.other, undefined, 'bootstrap must not execute the engine or depend on its availability');
  });
}

test('should preserve session identity without launching the engine when Claude starts', dir => {
  const launcher = path.join(dir, '.claude/skills/impeccable/scripts/impeccable');
  const envFile = path.join(dir, 'session.env');
  fs.mkdirSync(path.dirname(launcher), { recursive: true });
  fs.writeFileSync(launcher, '#!/bin/sh\nexit 99\n');
  const run = (session: string) => Bun.spawnSync(['node', path.join(repoRoot, 'scripts/impeccable/hook.cjs'), 'claude', 'SessionStart', 'hook'], {
    stdin: Buffer.from(JSON.stringify({ cwd: dir, session_id: session })),
    env: { ...process.env, CLAUDE_ENV_FILE: envFile },
  });

  assert.equal(run('session-123').exitCode, 0, 'startup must not depend on the engine');
  assert.equal(run('session-123').exitCode, 0, 'resume must succeed');
  assert.equal(fs.readFileSync(envFile, 'utf8'), "export IMPECCABLE_SESSION_ID='session-123'\n", 'identity must be exported only once');
  assert.equal(run("bad'; touch injected").exitCode, 0, 'unsafe identity must not stop setup guidance');
  assert.equal(fs.readFileSync(envFile, 'utf8'), "export IMPECCABLE_SESSION_ID='session-123'\n", 'unsafe identity must never reach the shell environment');
});

